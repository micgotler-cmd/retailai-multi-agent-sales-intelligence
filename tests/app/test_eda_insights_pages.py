@pytest.mark.parametrize("theme", ["light", "dark", None])
def test_charts_draw_the_summary_values_unchanged(tool_run, theme):
    tables = summary(tool_run)["tables"]
    category = charts.segment_bars(tables["category"], "cat_id", "Category", theme)
    assert list(category.data["avg_daily_units_per_item"]) == [
        r["avg_daily_units_per_item"] for r in tables["category"]
    ]
    weekday = charts.calendar_bars(tables["weekday"], "Weekday", theme)
    assert list(weekday.data["Weekday"]) == list(tables["weekday"])  # calendar order kept
    snap = charts.snap_bars(tables["snap"], theme)
    assert len(snap.data) == 2 * len(tables["snap"])
    events = charts.event_bars(tables["event_types"], theme).to_dict()
    assert "no event" not in json.dumps(events["datasets"])


def test_event_labels_carry_the_sign():
    rows = [
        {
            "event_type": "no event",
            "days": 9,
            "avg_daily_units_per_item": 1.8,
            "diff_vs_no_event_pct": 0.0,
        },
        {
            "event_type": "National",
            "days": 4,
            "avg_daily_units_per_item": 1.5,
            "diff_vs_no_event_pct": -14.7,
        },
        {
            "event_type": "Cultural",
            "days": 3,
            "avg_daily_units_per_item": 2.1,
            "diff_vs_no_event_pct": 18.2,
        },
    ]
    spec = json.dumps(charts.event_bars(rows).to_dict())
    assert '"-14.7%"' in spec and '"+18.2%"' in spec
    assert charts.COLORS["light"]["negative"] in spec

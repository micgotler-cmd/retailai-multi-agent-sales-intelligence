"""EDA and Business Insights pages (P-13 step 4) and their charts."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from app import charts
from src.repositories import run_artifacts as ra
from tests.app.test_streamlit_app import start

EDA = "pages/eda.py"
INSIGHTS = "pages/insights.py"


def set_report(run_dir: Path, **changes) -> None:
    path = run_dir / ra.REPORT_FILE
    report = json.loads(path.read_text(encoding="utf-8")) | changes
    path.write_text(json.dumps(report), encoding="utf-8")


def summary(run_dir: Path) -> dict:
    return json.loads((run_dir / "eda_summary.json").read_text(encoding="utf-8"))


def iframes(at) -> list:
    return [e for e in at.get("iframe")]


# ------------------------------------------------------------------------ EDA


def test_eda_page_embeds_the_report_and_offers_a_download(tool_run):
    at = start(EDA)
    assert len(iframes(at)) == 1
    assert at.get("download_button")[0].proto.label == "Download the EDA report (HTML)"
    assert not at.error


def test_eda_report_with_active_content_is_not_embedded(tool_run):
    report = tool_run / "eda_report.html"
    report.write_text(report.read_text(encoding="utf-8") + "<script>alert(1)</script>", "utf-8")
    at = start(EDA)
    assert not iframes(at)
    assert any("active content" in e.body for e in at.error)
    assert at.get("download_button")  # still available to inspect


@pytest.mark.parametrize("snippet", ['<img src=x onerror="x()">', '<a href="javascript:x()">'])
def test_event_handlers_and_script_links_count_as_active_content(tool_run, snippet):
    report = tool_run / "eda_report.html"
    report.write_text(report.read_text(encoding="utf-8") + snippet, "utf-8")
    assert not iframes(start(EDA))


def test_eda_page_without_the_report(tool_run):
    (tool_run / "eda_report.html").unlink()
    at = start(EDA)
    assert not iframes(at)
    assert any("no eda_report.html" in w.value for w in at.warning)


# ------------------------------------------------------------------- insights


def test_agent_insights_are_labeled_and_shown(tool_run):
    set_report(tool_run, insights_attempts=3)
    at = start(INSIGHTS)
    assert any("Written by the Business Analyst agent" in s.value for s in at.success)
    assert any("accepted on attempt 3" in s.value for s in at.success)
    first_line = (tool_run / "insights.md").read_text(encoding="utf-8").splitlines()[0]
    assert any(first_line.lstrip("# ") in m.value for m in at.markdown)


def test_fallback_insights_are_labeled_with_the_reason(tool_run):
    template = (tool_run / "insights.md").read_text(encoding="utf-8")
    note = "> **Fallback insights.** These insights were generated by the template.\n\n"
    (tool_run / "insights.md").write_text(ra.FALLBACK_MARKER + "\n" + note + template, "utf-8")
    set_report(tool_run, insights_source="template", fallback_reason="Agent 3 gave up")
    at = start(INSIGHTS)
    banner = " ".join(w.value for w in at.warning)
    assert "**Fallback insights.**" in banner and "because Agent 3 gave up" in banner
    shown = " ".join(m.value for m in at.markdown)
    assert ra.FALLBACK_MARKER not in shown and "These insights were generated" not in shown


def test_older_fallback_run_without_marker_is_labeled_from_the_report(tool_run):
    """Runs 1 and 2 were made before the marker existed; the report still says template."""
    set_report(tool_run, insights_source="template", fallback_reason=None)
    at = start(INSIGHTS)
    assert any("**Fallback insights.**" in w.value for w in at.warning)


def test_insights_cannot_inject_html(tool_run):
    (tool_run / "insights.md").write_text("# Insights\n\n<script>alert(1)</script>\n", "utf-8")
    at = start(INSIGHTS)
    md = [m for m in at.markdown if "<script>" in m.value]
    assert md and all(not m.proto.allow_html for m in md)


def test_six_charts_with_tables_and_the_fact_list(tool_run):
    facts = summary(tool_run)["facts"]
    at = start(INSIGHTS)
    assert len(at.get("vega_lite_chart")) == 6
    assert [s.value for s in at.subheader] == [
        "By category",
        "By demand group",
        "By weekday",
        "By month",
        "SNAP days vs other days",
        "Event days vs days without an event",
    ]
    labels = [e.label for e in at.expander]
    assert labels.count("Show as table") == 6
    assert f"All {len(facts)} facts cited as [Fnn]" in labels
    fact_table = at.dataframe[-1].value
    assert list(fact_table["Id"]) == [f["id"] for f in facts]
    assert (
        sum(c.value == "Descriptive association only, not a causal effect." for c in at.caption)
        == 2
    )



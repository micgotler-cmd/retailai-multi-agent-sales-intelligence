"""Evaluation report and model card (M-04, M-06): numbers and technical facts from Python.

Everything numeric or technical in `evaluation_report.md` and `model_card.md` is rendered here
from `metrics.json` and the feature schema, so the agent never has to reproduce it. Agent 6
writes only two short narrative texts (a summary and an interpretation), checked against the
numbered facts (`evaluation_text.py`). If the agent cannot produce checked text, a template
narrative built from the same facts is used and both files say so at the top.

The report keeps three things apart: the backtest (model comparison and tuning only), the
final test (scored once, by a model fitted before the test window) and the refitted model that
produces the future forecast (fitted on all history and not evaluated).
"""

from __future__ import annotations

from dataclasses import dataclass

import pandas as pd

from src.data.eda import fmt
from src.ml import feature_spec as spec
from src.ml.evaluation_text import BASELINE, MODEL_NAMES, UNIT, build_facts

AGENT_MARKER = "<!-- report_source: agent -->"
FALLBACK_MARKER = "<!-- report_source: template -->"
SOURCES = ("agent", "template")


@dataclass(frozen=True)
class Narrative:
    """The two text parts the agent (or the template) supplies."""

    summary: str
    interpretation: str


# ------------------------------------------------------------------ template narrative


def template_narrative(metrics: dict) -> Narrative:
    """A deterministic narrative that passes the same check as the agent's (tested)."""
    facts = build_facts(metrics)
    cite = {(f["topic"], f["metric"]): (f["id"], fmt(f["value"], f["unit"])) for f in facts}

    def num(topic: str, key: str, suffix: str = f" units per {UNIT.split('/')[1]}") -> str:
        fact_id, shown = cite[(topic, key)]
        return f"{shown} [{fact_id}]{suffix}"

    sel = metrics["selected_model"]
    other = next(m for m in ("ridge", "random_forest") if m != sel)
    name, other_name, base = MODEL_NAMES[sel], MODEL_NAMES[other], MODEL_NAMES[BASELINE]
    summary = (
        f"{name} was selected by the fixed rule: the lowest mean backtest MAE of the two "
        f"candidate models, with a backtest MAE of {num('backtest', f'{sel}_mae')} against "
        f"{other_name}'s backtest MAE of {num('backtest', f'{other}_mae')}. "
        f"On the final test window, {name} has a test MAE of {num('test', f'{sel}_mae')} and a "
        f"test RMSE of {num('test', f'{sel}_rmse')}, against {base}'s test MAE of "
        f"{num('test', f'{BASELINE}_mae')} and test RMSE of {num('test', f'{BASELINE}_rmse')}. "
        f"Against {base}, {name} has a test MAE difference of "
        f"{num('test', 'mae_improvement')} ({num('test', 'mae_improvement_pct', '')}); "
        "a positive difference means a smaller error for the model."
    )
    groups = [g for g in ("high", "medium", "low") if (("test_group", f"{sel}_{g}_mae") in cite)]
    bullets = [
        "- The backtest values compare the models during tuning; the test values are the single "
        "final evaluation on the held-out window; the refitted model behind the future forecast "
        "is not evaluated again.",
        *(
            f"- For the {g}-demand group, {name}'s test MAE is {num('test_group', f'{sel}_{g}_mae')} "
            f"and {base}'s test MAE is {num('test_group', f'{BASELINE}_{g}_mae')}."
            for g in groups
        ),
        "- Items with many zero-sales days are hard to forecast; see the limitations section.",
    ]
    return Narrative(summary, "\n".join(bullets))


# ------------------------------------------------------------------------------ pieces


def _table(headers: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def _f(value: float) -> str:
    return f"{value:.4f}"


def _params(params: dict) -> str:
    return ", ".join(f"{k} = {v}" for k, v in params.items()) or "none"


def _banner(source: str, reason: str | None, what: str) -> str:
    if source == "template":
        return (
            f"{FALLBACK_MARKER}\n> **Fallback {what}.** The narrative sections were generated by "
            f"the deterministic template (Python), not written by the Model Evaluator agent, "
            f"because {reason}. All tables and technical sections are generated by Python in "
            "either case.\n"
        )
    return f"{AGENT_MARKER}\n"


def _check_source(source: str) -> None:
    if source not in SOURCES:
        raise ValueError(f"source must be one of {SOURCES}")


def _future_dates(metrics: dict) -> tuple[str, str]:
    last = pd.Timestamp(metrics["test"]["last_date"])
    return (
        (last + pd.Timedelta(days=1)).date().isoformat(),
        (last + pd.Timedelta(days=metrics["horizon_days"])).date().isoformat(),
    )


LIMITATIONS = [
    "Intermittent demand: items with many zero-sales days are forecast poorly, and the error "
    "per item-day is dominated by a few busy items.",
    "No inventory data: forecasts are expected sales, not demand lost to stock-outs, and say "
    "nothing about stock levels.",
    "One store (`{store}`) and {items} items: the results do not carry over to other stores or "
    "items.",
    "Prices and promotions are not model inputs (M5 has no promotion field and future prices "
    "are unknown at the forecast origin, D-07).",
    "SNAP days, events and calendar effects are used as inputs; the model describes "
    "associations and makes no causal claims.",
    "The test window is a single {horizon}-day period; its scores are one measurement, with no "
    "confidence interval.",
    "Predictions are clipped at zero and are not rounded to whole units.",
    "The narrative sections are checked so that every number is a computed, correctly labeled "
    "result and unsupported claims are rejected. That check does not guarantee that every "
    "conclusion is semantically correct; a person must review this document.",
]


def _limitations(metrics: dict) -> str:
    fill = {
        "store": metrics["store_id"],
        "items": metrics["n_items"],
        "horizon": metrics["horizon_days"],
    }
    return "\n".join(f"- {line.format(**fill)}" for line in LIMITATIONS)


# ------------------------------------------------------------------ evaluation report


def render_evaluation_report(
    metrics: dict, narrative: Narrative, source: str, reason: str | None = None
) -> str:
    """The full `evaluation_report.md`."""
    _check_source(source)
    sel = metrics["selected_model"]
    sel_name = MODEL_NAMES[sel]
    selection = metrics["selection"]
    test = metrics["test"]
    base_test = test["seasonal_naive"]
    windows = metrics["models"][sel]["backtest"]["windows"]
    models = [BASELINE, "ridge", "random_forest"]
    mean_rows = [
        [
            MODEL_NAMES[m],
            _f(metrics["models"][m]["backtest"]["mean_overall"]["mae"]),
            _f(metrics["models"][m]["backtest"]["mean_overall"]["rmse"]),
            *[_f(w["overall"]["mae"]) for w in metrics["models"][m]["backtest"]["windows"]],
        ]
        for m in models
    ]
    window_headers = [f"MAE {w['window']} ({w['first_date']} to {w['last_date']})" for w in windows]
    candidate_rows = [
        [
            MODEL_NAMES[c["model"]],
            _params(c["hyperparameters"]),
            _f(c["mean_overall"]["mae"]),
            _f(c["mean_overall"]["rmse"]),
        ]
        for c in metrics["backtest_candidates"]
    ]
    test_rows = [
        [name, _f(s["overall"]["mae"]), _f(s["overall"]["rmse"])]
        for name, s in ((sel_name, test), (MODEL_NAMES[BASELINE], base_test))
    ]
    group_rows = [
        [
            group,
            entry["n_items"],
            _f(entry["mae"]),
            _f(base_test["per_demand_group"][group]["mae"]),
            _f(entry["rmse"]),
            _f(base_test["per_demand_group"][group]["rmse"]),
        ]
        for group, entry in test["per_demand_group"].items()
    ]
    item_rows = [
        [
            item,
            entry["demand_group"],
            _f(entry["mae"]),
            _f(base_test["per_item"][item]["mae"]),
            _f(entry["rmse"]),
            _f(base_test["per_item"][item]["rmse"]),
        ]
        for item, entry in test["per_item"].items()
    ]
    first_future, last_future = _future_dates(metrics)
    verdict = "beats" if selection["beats_baseline_on_backtest"] else "does not beat"
    parts = [
        _banner(source, reason, "report"),
        "# Evaluation report\n",
        f"Run `{metrics['run_id']}` | store `{metrics['store_id']}` | {metrics['n_items']} items "
        f"| {metrics['horizon_days']}-day horizon | schema {metrics['schema_version']}\n",
        f"## 1. Summary\n\n{narrative.summary.strip()}\n",
        "## 2. Method and windows\n",
        f"- Models: {', '.join(MODEL_NAMES[m] for m in models)}. One global model per variant "
        "across all items; Seasonal Naive repeats the last 7 observed days (T-23).\n"
        f"- Primary selection metric: {selection['metric']} (lower is better), seed "
        f"{selection['seed']}. Tie-break: {selection['tie_break']}.\n"
        f"- Hyperparameter grids ({selection['n_candidates']} candidates): "
        + "; ".join(f"{MODEL_NAMES[m]}: {g}" for m, g in selection["grids"].items())
        + ".\n- Predictions are clipped at 0 in the backtest, the test forecast and the future "
        "forecast alike.\n- Backtest windows: "
        + "; ".join(
            f"{w['window']} origin {w['origin_date']}, forecast {w['first_date']} to "
            f"{w['last_date']}"
            for w in windows
        )
        + f".\n- Test window: origin {test['origin_date']}, forecast {test['first_date']} to "
        f"{test['last_date']}.\n",
        "## 3. Model selection: rolling-origin backtest (comparison and tuning only)\n",
        "These scores choose the model and its hyperparameters. They are not the final "
        "performance estimate. Values are MAE and RMSE in units per item-day (4 decimals).\n",
        _table(["Model", "Mean MAE", "Mean RMSE", *window_headers], mean_rows),
        "\nAll candidates, by mean backtest MAE and RMSE:\n",
        _table(["Model", "Hyperparameters", "Mean MAE", "Mean RMSE"], candidate_rows),
        f"\nSelected: **{sel_name}** ({_params(selection['selected_hyperparameters'])}), by the "
        f"deterministic rule only. On the backtest it {verdict} Seasonal Naive "
        f"({_f(selection['selected_mean_backtest_mae'])} against "
        f"{_f(selection['baseline_mean_backtest_mae'])} mean MAE).\n",
        f"## 4. Final test results (scored once, model fitted through day "
        f"{test['fitted_through_day']})\n",
        "The test window was never used for fitting, selection or tuning. Only the selected "
        "model and the baseline are scored on it.\n",
        _table(["Model", "MAE", "RMSE"], test_rows),
        f"\nMAE improvement of {sel_name} over Seasonal Naive: "
        f"{_f(test['improvement_over_baseline_mae'])} units per item-day.\n",
        f"By demand group ({sel_name} versus Seasonal Naive):\n",
        _table(
            [
                "Group",
                "Items",
                f"{sel_name} MAE",
                "Seasonal Naive MAE",
                f"{sel_name} RMSE",
                "Seasonal Naive RMSE",
            ],
            group_rows,
        ),
        "\nBy item:\n",
        _table(
            [
                "Item",
                "Group",
                f"{sel_name} MAE",
                "Seasonal Naive MAE",
                f"{sel_name} RMSE",
                "Seasonal Naive RMSE",
            ],
            item_rows,
        ),
        "\n## 5. Refitted forecasting model (not evaluated)\n",
        f"After the test score was recorded, {sel_name} was refitted with the same "
        f"hyperparameters on all history through day {metrics['refit']['fitted_through_day']} "
        f"(model version `{metrics['refit']['model_version']}`) and forecast {first_future} to "
        f"{last_future} (`forecast.csv`). The test metrics above were not recomputed and this "
        "model has no test score of its own.\n",
        f"## 6. Interpretation\n\n{narrative.interpretation.strip()}\n",
        f"## 7. Limitations\n\n{_limitations(metrics)}\n",
    ]
    return "\n".join(parts)


# ------------------------------------------------------------------------------ model card


def render_model_card(
    metrics: dict, narrative: Narrative, source: str, reason: str | None = None
) -> str:
    """The full `model_card.md` (M-06)."""
    _check_source(source)
    sel = metrics["selected_model"]
    sel_name = MODEL_NAMES[sel]
    selection = metrics["selection"]
    test = metrics["test"]
    first_future, last_future = _future_dates(metrics)
    mean = metrics["models"]
    rows = [
        [
            "Backtest mean (tuning only)",
            _f(mean[sel]["backtest"]["mean_overall"]["mae"]),
            _f(mean[sel]["backtest"]["mean_overall"]["rmse"]),
            _f(mean[BASELINE]["backtest"]["mean_overall"]["mae"]),
            _f(mean[BASELINE]["backtest"]["mean_overall"]["rmse"]),
        ],
        [
            "Final test (scored once)",
            _f(test["overall"]["mae"]),
            _f(test["overall"]["rmse"]),
            _f(test["seasonal_naive"]["overall"]["mae"]),
            _f(test["seasonal_naive"]["overall"]["rmse"]),
        ],
    ]
    categorical = ", ".join(f"`{c}`" for c in spec.CATEGORICAL_FEATURES)
    numeric = ", ".join(f"`{c}`" for c in spec.NUMERIC_FEATURES)
    parts = [
        _banner(source, reason, "model card"),
        f"# Model card: {sel_name} sales forecast\n",
        f"Run `{metrics['run_id']}` | model version `{metrics['refit']['model_version']}`\n",
        "## Purpose and intended use\n",
        f"Forecast daily unit sales for {metrics['n_items']} products in store "
        f"`{metrics['store_id']}` for the next {metrics['horizon_days']} days, to support "
        "stock and staffing discussions. Forecasts are expected values for human review, not "
        "automatic orders.\n",
        "## Training data\n",
        f"Walmart M5 sales for store `{metrics['store_id']}` (Kaggle, used locally; the data is "
        f"not redistributed). {metrics['n_items']} items chosen by a fixed rule on the training "
        "period only (7 high, 7 medium, 6 low demand). History runs from each item's first sale "
        f"to day {metrics['refit']['fitted_through_day']} (ending {test['last_date']}). Days "
        "before an item's first sale are removed, store-closure days are flagged and no values "
        "are imputed.\n",
        "## Model\n",
        f"- Selected variant: **{sel_name}** ({_params(selection['selected_hyperparameters'])}), "
        f"chosen by {selection['metric']} on the backtest windows only (seed "
        f"{selection['seed']}).\n"
        f"- One global model for all items; direct {metrics['horizon_days']}-day forecasting, no "
        "recursive prediction.\n"
        f"- Numeric features: {numeric}. Categorical features (one-hot encoded): {categorical}. "
        f"Sales-based features use only data at least {spec.MIN_LOOKBACK_DAYS} days before the "
        "target day. `sell_price` is not used.\n"
        "- Predictions are clipped at 0.\n",
        "## Evaluation\n",
        "Values are MAE and RMSE in units per item-day. The final test row comes from a model "
        f"fitted through day {test['fitted_through_day']}; the deployed model was refitted on "
        f"all history through day {metrics['refit']['fitted_through_day']} and has no test "
        "score of its own.\n",
        _table(
            [
                "Evaluation",
                f"{sel_name} MAE",
                f"{sel_name} RMSE",
                "Seasonal Naive MAE",
                "Seasonal Naive RMSE",
            ],
            rows,
        ),
        f"\n{narrative.summary.strip()}\n",
        f"Forecast produced: {first_future} to {last_future} (`forecast.csv`). Full details in "
        "`evaluation_report.md`.\n",
        f"## Limitations\n\n{_limitations(metrics)}\n",
        "## Ethical considerations\n",
        "- Forecasts may influence stock and staffing decisions; a poor forecast can cause "
        "overstock or empty shelves, so a person should review them.\n"
        "- The model is trained on one store; it must not be used to judge other stores or to "
        "evaluate staff.\n"
        "- The data holds no personal information.\n",
        "## Reproducibility\n",
        f"Fixed seed {selection['seed']}; the same inputs give identical results. The fitted "
        "pipelines for both variants, with their preprocessing, are stored in `model.joblib` "
        "(load only files this pipeline wrote).\n",
    ]
    return "\n".join(parts)

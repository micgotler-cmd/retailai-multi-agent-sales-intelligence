"""Exploratory Data Analysis: the EDA report written by Agent 3's tool, shown as is.

eda_report.html is generated by src/data/eda.py, not by the LLM: every value is
HTML-escaped, charts are embedded as images and there are no scripts. st.iframe
runs embedded HTML with scripts and same-origin access, so as a safety net a
report that contains a script or an event handler is not embedded, only offered
as a download. Never pass LLM text or user input to st.iframe.
"""

from __future__ import annotations

import re

import streamlit as st

from app import common

REPORT = "eda_report.html"
ACTIVE_CONTENT = re.compile(
    r"<script|<iframe|<object|<embed|javascript:|\son\w+\s*=", re.IGNORECASE
)

st.title("Exploratory Data Analysis")
run = common.selected_run()
if run is not None:
    html = run.text(REPORT)
    if html is None:
        common.missing_files_message(run, [REPORT])
    else:
        st.caption(
            "Training period only (T-09). Computed by deterministic Python; differences for "
            "SNAP days, events and prices are associations, not causal effects."
        )
        st.download_button(
            "Download the EDA report (HTML)",
            data=html.encode("utf-8"),
            file_name=f"eda_report_{run.run_id}.html",
            mime="text/html",
        )
        if ACTIVE_CONTENT.search(html):
            st.error(
                "This report contains active content (scripts or event handlers), which the "
                "EDA step never writes, so it is not displayed here. Check the run folder."
            )
        else:
            st.iframe(html, height=1400)

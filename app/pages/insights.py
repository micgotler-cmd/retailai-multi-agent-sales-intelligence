"""Business Insights: insights.md with its source clearly labeled, and charts of the EDA facts.

The text is shown as plain Markdown (no raw HTML). Every number in it cites a
fact id [Fnn] that is listed below the text. The charts draw the tables of
eda_summary.json; nothing is computed here.
"""

from __future__ import annotations

import pandas as pd
import streamlit as st

from app import charts, common
from src.data.eda import fmt

SUMMARY = "eda_summary.json"
NOT_CAUSAL = "Descriptive association only, not a causal effect."


def _theme() -> str | None:
    try:
        return st.context.theme.type  # "light" or "dark" (Streamlit 1.46+)
    except AttributeError:
        return None


def _without_fallback_note(text: str) -> str:
    """Drop the fallback note at the top (the banner above shows the same reason)."""
    lines = text.splitlines()
    while lines and (lines[0].startswith(">") or not lines[0].strip()):
        lines.pop(0)
    return "\n".join(lines)


def _source_banner(report: dict | None, fallback_marker: bool) -> None:
    report = report or {}
    source = report.get("insights_source")
    if fallback_marker or source == "template":
        reason = report.get("fallback_reason") or "the agent's insights did not pass the check"
        st.warning(
            "**Fallback insights.** Generated by the deterministic template (Python), not "
            f"written by the Business Analyst agent, because {reason}. Every number is a "
            "computed fact."
        )
    elif source == "agent":
        attempts = report.get("insights_attempts")
        tries = f" (accepted on attempt {attempts})" if attempts else ""
        st.success(
            "**Written by the Business Analyst agent.** Every number passed the automatic "
            f"citation check against the computed facts{tries}."
        )
    else:
        st.info("The source of these insights is not recorded for this run.")


def _table(rows, columns: dict[str, str]) -> None:
    with st.expander("Show as table"):
        st.dataframe(
            pd.DataFrame(rows)[list(columns)].rename(columns=columns),
            hide_index=True,
            width="stretch",
        )


st.title("Business Insights")
run = common.selected_run()
if run is not None:
    text, marker = run.insights()
    summary = run.json(SUMMARY)
    common.missing_files_message(run, ["insights.md", SUMMARY])

    if text is not None:
        _source_banner(run.report, marker)
        st.markdown(_without_fallback_note(text) if marker else text)

    if summary is not None:
        tables = summary.get("tables") or {}
        theme = _theme()
        period = summary.get("period") or {}
        st.header("Demand patterns")
        st.caption(
            f"Training period {period.get('first_date', '?')} to {period.get('last_date', '?')}"
            " (T-09). Averages are per item per day, so groups of different sizes compare "
            "fairly; closure days are excluded."
        )
        avg = {"avg_daily_units_per_item": "Average daily units per item"}

        col1, col2 = st.columns(2)
        with col1:
            st.subheader("By category")
            if tables.get("category"):
                st.altair_chart(
                    charts.segment_bars(tables["category"], "cat_id", "Category", theme),
                    width="stretch",
                )
                _table(tables["category"], {"cat_id": "Category", "items": "Items"} | avg)
        with col2:
            st.subheader("By demand group")
            if tables.get("demand_group"):
                st.altair_chart(
                    charts.segment_bars(tables["demand_group"], "demand_group", "Group", theme),
                    width="stretch",
                )
                _table(
                    tables["demand_group"], {"demand_group": "Demand group", "items": "Items"} | avg
                )

        col1, col2 = st.columns(2)
        for col, key, label in ((col1, "weekday", "Weekday"), (col2, "month", "Month")):
            with col:
                st.subheader(f"By {label.lower()}")
                if tables.get(key):
                    st.altair_chart(
                        charts.calendar_bars(tables[key], label, theme), width="stretch"
                    )
                    _table(
                        [{label: k, "avg": v} for k, v in tables[key].items()],
                        {label: label, "avg": "Average daily units per item"},
                    )

        col1, col2 = st.columns(2)
        with col1:
            st.subheader("SNAP days vs other days")
            if tables.get("snap"):
                st.altair_chart(charts.snap_bars(tables["snap"], theme), width="stretch")
                st.caption(NOT_CAUSAL)
                _table(
                    tables["snap"],
                    {
                        "segment": "Segment",
                        "with": "SNAP days",
                        "without": "Other days",
                        "diff_pct": "Difference (%)",
                    },
                )
        with col2:
            st.subheader("Event days vs days without an event")
            if tables.get("event_types"):
                st.altair_chart(charts.event_bars(tables["event_types"], theme), width="stretch")
                st.caption(NOT_CAUSAL)
                _table(
                    tables["event_types"],
                    {
                        "event_type": "Event type",
                        "days": "Days",
                        "avg_daily_units_per_item": "Average daily units per item",
                        "diff_vs_no_event_pct": "Difference vs no event (%)",
                    },
                )

        facts = summary.get("facts") or []
        if facts:
            with st.expander(f"All {len(facts)} facts cited as [Fnn]"):
                st.dataframe(
                    [
                        {
                            "Id": f.get("id"),
                            "Value": fmt(f.get("value"), f.get("unit", "")),
                            "Unit": f.get("unit"),
                            "Definition": f.get("definition"),
                        }
                        for f in facts
                    ],
                    hide_index=True,
                    width="stretch",
                )
